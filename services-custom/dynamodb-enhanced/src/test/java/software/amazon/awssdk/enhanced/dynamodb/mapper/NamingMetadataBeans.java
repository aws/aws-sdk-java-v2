package software.amazon.awssdk.enhanced.dynamodb.mapper;

import java.beans.Transient;
import java.time.Instant;
import java.util.List;
import software.amazon.awssdk.enhanced.dynamodb.extensions.annotations.DynamoDbAtomicCounter;
import software.amazon.awssdk.enhanced.dynamodb.extensions.annotations.DynamoDbAutoGeneratedTimestampAttribute;
import software.amazon.awssdk.enhanced.dynamodb.extensions.annotations.DynamoDbAutoGeneratedUuid;
import software.amazon.awssdk.enhanced.dynamodb.extensions.annotations.DynamoDbVersionAttribute;
import software.amazon.awssdk.enhanced.dynamodb.mapper.UpdateBehavior;
import software.amazon.awssdk.enhanced.dynamodb.mapper.annotations.DynamoDbAttribute;
import software.amazon.awssdk.enhanced.dynamodb.mapper.annotations.DynamoDbBean;
import software.amazon.awssdk.enhanced.dynamodb.mapper.annotations.DynamoDbFlatten;
import software.amazon.awssdk.enhanced.dynamodb.mapper.annotations.DynamoDbIgnore;
import software.amazon.awssdk.enhanced.dynamodb.mapper.annotations.DynamoDbIgnoreNulls;
import software.amazon.awssdk.enhanced.dynamodb.mapper.annotations.DynamoDbPartitionKey;
import software.amazon.awssdk.enhanced.dynamodb.mapper.annotations.DynamoDbPreserveEmptyObject;
import software.amazon.awssdk.enhanced.dynamodb.mapper.annotations.DynamoDbSearchVectorsHashKey;
import software.amazon.awssdk.enhanced.dynamodb.mapper.annotations.DynamoDbSearchVectorsInlineFilterKey;
import software.amazon.awssdk.enhanced.dynamodb.mapper.annotations.DynamoDbSecondaryPartitionKey;
import software.amazon.awssdk.enhanced.dynamodb.mapper.annotations.DynamoDbSecondarySortKey;
import software.amazon.awssdk.enhanced.dynamodb.mapper.annotations.DynamoDbSortKey;
import software.amazon.awssdk.enhanced.dynamodb.mapper.annotations.DynamoDbUpdateBehavior;
import software.amazon.awssdk.enhanced.dynamodb.mapper.annotations.DynamoDbVectorAttribute;
import software.amazon.awssdk.enhanced.dynamodb.model.DistanceFunction;

/**
 * Beans whose annotations record stored names in table metadata.
 */
final class NamingMetadataBeans {
    static final String GSI_EMAIL = "gsi-email";
    static final String LSI_CREATED = "lsi-created";
    static final String GSI_REGION = "gsi-region";
    static final String VECTOR_INDEX = "embedding-index";

    private NamingMetadataBeans() {
    }

    /**
     * A superclass whose properties are scanned with the subclass schema.
     */
    public static class MetadataBase {
        private String accountId;
        private String legacyCode;

        public String getAccountId() {
            return accountId;
        }

        public void setAccountId(String accountId) {
            this.accountId = accountId;
        }

        @DynamoDbAttribute("LEGACY")
        public String getLegacyCode() {
            return legacyCode;
        }

        public void setLegacyCode(String legacyCode) {
            this.legacyCode = legacyCode;
        }
    }

    /**
     * A bean that records keys, indexes, extensions, and vector names.
     */
    @DynamoDbBean
    public static class MetadataBean extends MetadataBase {
        private String id;
        private String orderId;
        private String emailAddress;
        private String createdOn;
        private Long recordVersion;
        private Long hitCount;
        private String requestId;
        private Instant updatedAt;
        private String statusCode;
        private String secret;
        private String cache;
        private String productCategory;
        private String brandName;
        private List<Float> productEmbedding;

        @DynamoDbPartitionKey
        public String getId() {
            return id;
        }

        public void setId(String id) {
            this.id = id;
        }

        @DynamoDbSortKey
        public String getOrderId() {
            return orderId;
        }

        public void setOrderId(String orderId) {
            this.orderId = orderId;
        }

        @DynamoDbSecondaryPartitionKey(indexNames = GSI_EMAIL)
        public String getEmailAddress() {
            return emailAddress;
        }

        public void setEmailAddress(String emailAddress) {
            this.emailAddress = emailAddress;
        }

        @DynamoDbSecondarySortKey(indexNames = {LSI_CREATED, GSI_EMAIL})
        public String getCreatedOn() {
            return createdOn;
        }

        public void setCreatedOn(String createdOn) {
            this.createdOn = createdOn;
        }

        @DynamoDbVersionAttribute
        public Long getRecordVersion() {
            return recordVersion;
        }

        public void setRecordVersion(Long recordVersion) {
            this.recordVersion = recordVersion;
        }

        @DynamoDbAtomicCounter
        public Long getHitCount() {
            return hitCount;
        }

        public void setHitCount(Long hitCount) {
            this.hitCount = hitCount;
        }

        @DynamoDbAutoGeneratedUuid
        public String getRequestId() {
            return requestId;
        }

        public void setRequestId(String requestId) {
            this.requestId = requestId;
        }

        @DynamoDbAutoGeneratedTimestampAttribute
        public Instant getUpdatedAt() {
            return updatedAt;
        }

        public void setUpdatedAt(Instant updatedAt) {
            this.updatedAt = updatedAt;
        }

        @DynamoDbUpdateBehavior(UpdateBehavior.WRITE_IF_NOT_EXISTS)
        public String getStatusCode() {
            return statusCode;
        }

        public void setStatusCode(String statusCode) {
            this.statusCode = statusCode;
        }

        @DynamoDbIgnore
        public String getSecret() {
            return secret;
        }

        public void setSecret(String secret) {
            this.secret = secret;
        }

        @Transient
        public String getCache() {
            return cache;
        }

        public void setCache(String cache) {
            this.cache = cache;
        }

        @DynamoDbSearchVectorsHashKey(indexNames = VECTOR_INDEX)
        public String getProductCategory() {
            return productCategory;
        }

        public void setProductCategory(String productCategory) {
            this.productCategory = productCategory;
        }

        @DynamoDbSearchVectorsInlineFilterKey(indexNames = VECTOR_INDEX)
        public String getBrandName() {
            return brandName;
        }

        public void setBrandName(String brandName) {
            this.brandName = brandName;
        }

        @DynamoDbVectorAttribute(indexName = VECTOR_INDEX, dimensions = 3, distanceFunction = DistanceFunction.COSINE)
        public List<Float> getProductEmbedding() {
            return productEmbedding;
        }

        public void setProductEmbedding(List<Float> productEmbedding) {
            this.productEmbedding = productEmbedding;
        }
    }

    /**
     * A flattened child that contributes key names to the parent.
     */
    @DynamoDbBean
    public static class KeyChild {
        private String customerId;
        private String regionCode;

        @DynamoDbPartitionKey
        public String getCustomerId() {
            return customerId;
        }

        public void setCustomerId(String customerId) {
            this.customerId = customerId;
        }

        @DynamoDbSecondaryPartitionKey(indexNames = GSI_REGION)
        public String getRegionCode() {
            return regionCode;
        }

        public void setRegionCode(String regionCode) {
            this.regionCode = regionCode;
        }
    }

    /**
     * A parent that flattens {@link KeyChild}.
     */
    @DynamoDbBean
    public static class KeyParent {
        private KeyChild child;

        @DynamoDbFlatten
        public KeyChild getChild() {
            return child;
        }

        public void setChild(KeyChild child) {
            this.child = child;
        }
    }

    /**
     * A nested object used by the empty-object and ignore-nulls checks.
     */
    @DynamoDbBean
    public static class EmptyChild {
        private String cityName;

        public String getCityName() {
            return cityName;
        }

        public void setCityName(String cityName) {
            this.cityName = cityName;
        }
    }

    /**
     * A parent that preserves an empty child and ignores nulls in another child.
     */
    @DynamoDbBean
    public static class EmptyParent {
        private String id;
        private EmptyChild preserved;
        private EmptyChild skipped;

        @DynamoDbPartitionKey
        public String getId() {
            return id;
        }

        public void setId(String id) {
            this.id = id;
        }

        @DynamoDbPreserveEmptyObject
        public EmptyChild getPreserved() {
            return preserved;
        }

        public void setPreserved(EmptyChild preserved) {
            this.preserved = preserved;
        }

        @DynamoDbIgnoreNulls
        public EmptyChild getSkipped() {
            return skipped;
        }

        public void setSkipped(EmptyChild skipped) {
            this.skipped = skipped;
        }
    }
}
