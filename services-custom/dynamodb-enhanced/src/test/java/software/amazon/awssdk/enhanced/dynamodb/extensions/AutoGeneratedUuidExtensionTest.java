    @Test
    public void beforeWrite_updateItem_whenNonKeyCreateAttributeIsMissing_usesIfNotExists() {
        Map<String, AttributeValue> rawItems = new HashMap<>();
        rawItems.put("id", AttributeValue.fromS(RECORD_ID));

        WriteModification result =
            uuidExtension.beforeWrite(
                DefaultDynamoDbExtensionContext.builder()
                                               .items(rawItems)
                                               .tableMetadata(ITEM_WITH_CREATE_UUID_MAPPER.tableMetadata())
                                               .operationName(OperationName.UPDATE_ITEM)
                                               .operationContext(PRIMARY_CONTEXT)
                                               .build());

        assertThat(result.transformedItem()).doesNotContainKey("uuidAttribute");
        assertThat(result.updateExpression().setActions()).hasSize(1);
        SetAction action = result.updateExpression().setActions().get(0);
        String valueToken = action.expressionValues().keySet().iterator().next();
        assertThat(action.expressionNames()).containsEntry(action.path(), "uuidAttribute");
        assertThat(action.value()).isEqualTo("if_not_exists(" + action.path() + ", " + valueToken + ")");
        assertThat(isValidUuid(action.expressionValues().get(valueToken).s())).isTrue();
    }

    @Test
    public void beforeWrite_updateItem_whenPrimaryKeyCreateAttributeIsMissing_generatesUuidInTransformedItem() {
        StaticTableSchema<ItemWithUuid> primaryKeyCreateSchema =
            StaticTableSchema.builder(ItemWithUuid.class)
                             .newItemSupplier(ItemWithUuid::new)
                             .addAttribute(String.class, a -> a.name("id")
                                                               .getter(ItemWithUuid::getId)
                                                               .setter(ItemWithUuid::setId)
                                                               .tags(primaryPartitionKey(),
                                                                     AutoGeneratedUuidExtension.AttributeTags
                                                                         .autoGeneratedUuidAttribute(
                                                                             DynamoDbAutoGenerateStrategy.CREATE)))
                             .build();

        WriteModification result =
            uuidExtension.beforeWrite(
                DefaultDynamoDbExtensionContext.builder()
                                               .items(new HashMap<>())
                                               .tableMetadata(primaryKeyCreateSchema.tableMetadata())
                                               .operationName(OperationName.UPDATE_ITEM)
                                               .operationContext(PRIMARY_CONTEXT)
                                               .build());

        assertThat(isValidUuid(result.transformedItem().get("id").s())).isTrue();
        assertThat(result.updateExpression()).isNull();
    }

    @Test
    public void beforeWrite_updateItem_whenMultipleCreateAttributesHaveDifferentRepresentations_buildsExpectedModifications() {
        Map<String, AttributeValue> rawItems = new HashMap<>();
        rawItems.put("id", AttributeValue.fromS(RECORD_ID));
        rawItems.put("explicitNullCreateUuid", AttributeValue.fromNul(true));

        WriteModification result =
            uuidExtension.beforeWrite(
                DefaultDynamoDbExtensionContext.builder()
                                               .items(rawItems)
                                               .tableMetadata(ITEM_WITH_MULTIPLE_CREATE_UUIDS_MAPPER.tableMetadata())
                                               .operationName(OperationName.UPDATE_ITEM)
                                               .operationContext(PRIMARY_CONTEXT)
                                               .build());

        assertThat(result.transformedItem()).doesNotContainKeys("firstCreateUuid", "gsiCreateUuid");
        assertThat(isValidUuid(result.transformedItem().get("explicitNullCreateUuid").s())).isTrue();

        List<SetAction> actions = result.updateExpression().setActions();
        assertThat(actions).hasSize(2);
        assertThat(actions).extracting(SetAction::expressionNames)
                           .anySatisfy(names -> assertThat(names).containsValue("firstCreateUuid"))
                           .anySatisfy(names -> assertThat(names).containsValue("gsiCreateUuid"));
        assertThat(actions).flatExtracting(action -> action.expressionValues().values())
                           .allSatisfy(value -> assertThat(isValidUuid(value.s())).isTrue());
        assertThat(actions).extracting(SetAction::path).doesNotHaveDuplicates();
    }

