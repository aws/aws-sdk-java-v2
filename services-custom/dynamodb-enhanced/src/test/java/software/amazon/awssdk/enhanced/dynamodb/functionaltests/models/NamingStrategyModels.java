    /**
     * A value written by {@link TokenConverter}.
     */
    public static final class NamingToken {
        private final String value;

        public NamingToken(String value) {
            this.value = value;
        }

        public String value() {
            return value;
        }

        @Override
        public boolean equals(Object other) {
            if (this == other) {
                return true;
            }
            if (other == null || getClass() != other.getClass()) {
                return false;
            }
            return Objects.equals(value, ((NamingToken) other).value);
        }

        @Override
        public int hashCode() {
            return Objects.hashCode(value);
        }
    }

    /**
     * Writes {@link NamingToken} with a fixed prefix.
     */
    public static final class TokenConverter implements AttributeConverter<NamingToken> {
        @Override
        public AttributeValue transformFrom(NamingToken input) {
            return AttributeValue.fromS(TOKEN_PREFIX + input.value());
        }

        @Override
        public NamingToken transformTo(AttributeValue input) {
            return new NamingToken(input.s().substring(TOKEN_PREFIX.length()));
        }

        @Override
        public EnhancedType<NamingToken> type() {
            return EnhancedType.of(NamingToken.class);
        }

        @Override
        public AttributeValueType attributeValueType() {
            return AttributeValueType.S;
        }
    }

