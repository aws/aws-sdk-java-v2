package software.amazon.awssdk.enhanced.dynamodb.functionaltests.extensions;

import static org.assertj.core.api.Assertions.assertThat;

import java.util.Collection;
import java.util.Collections;
import java.util.Map;
import org.junit.After;
import org.junit.Before;
import org.junit.Test;
import org.junit.runner.RunWith;
import org.junit.runners.Parameterized;
import software.amazon.awssdk.enhanced.dynamodb.DynamoDbEnhancedClient;
import software.amazon.awssdk.enhanced.dynamodb.DynamoDbTable;
import software.amazon.awssdk.enhanced.dynamodb.extensions.AutoGeneratedTimestampRecordExtension;
import software.amazon.awssdk.enhanced.dynamodb.functionaltests.LocalDynamoDbSyncTestBase;
import software.amazon.awssdk.enhanced.dynamodb.functionaltests.NamingStrategySupport;
import software.amazon.awssdk.enhanced.dynamodb.functionaltests.models.NamingStrategyModels.NamingEvent;
import software.amazon.awssdk.enhanced.dynamodb.functionaltests.models.NamingStrategyModels.NamingTimestampItem;
import software.amazon.awssdk.enhanced.dynamodb.mapper.AttributeNamingStrategy;
import software.amazon.awssdk.services.dynamodb.model.AttributeValue;
import software.amazon.awssdk.services.dynamodb.model.ResourceNotFoundException;

/**
 * Checks that the timestamp extension writes the resolved attribute name.
 * A list of events keeps the resolved list name.
 */
@RunWith(Parameterized.class)
public class AttributeNamingStrategyAutoGeneratedTimestampTest extends LocalDynamoDbSyncTestBase {

    @Parameterized.Parameter(0)
    public String strategyName;

    @Parameterized.Parameter(1)
    public AttributeNamingStrategy strategy;

    private DynamoDbTable<NamingTimestampItem> mappedTable;
    private String tableName;

    /**
     * Returns the five naming strategies.
     */
    @Parameterized.Parameters(name = "{0}")
    public static Collection<Object[]> parameters() {
        return NamingStrategySupport.parameters();
    }

    /**
     * Creates a client that includes the timestamp extension.
     */
    @Before
    public void createTable() {
        DynamoDbEnhancedClient enhancedClient = DynamoDbEnhancedClient.builder()
                                                                      .dynamoDbClient(getDynamoDbClient())
                                                                      .extensions(AutoGeneratedTimestampRecordExtension.create())
                                                                      .build();
        tableName = getConcreteTableName("naming-timestamp");
        mappedTable = enhancedClient.table(tableName, NamingStrategySupport.beanSchema(NamingTimestampItem.class, strategy));
        mappedTable.createTable();
    }

    /**
     * Deletes the timestamp table.
     */
    @After
    public void deleteTable() {
        try {
            getDynamoDbClient().deleteTable(request -> request.tableName(tableName));
        } catch (ResourceNotFoundException ignored) {
            // The table was not created.
        }
    }

    @Test
    public void putItem_whenTimestampExtension_writesResolvedNames() {
        NamingTimestampItem item = new NamingTimestampItem();
        item.setId("id-1");
        item.setEventRecords(Collections.singletonList(new NamingEvent()));
        mappedTable.putItem(item);

        Map<String, AttributeValue> stored = NamingStrategySupport.lowLevelByKey(getDynamoDbClient(), tableName, NamingStrategySupport.stored(strategy, "id"), "id-1");
        String updatedAt = NamingStrategySupport.stored(strategy, "updatedAt");
        String eventRecords = NamingStrategySupport.stored(strategy, "eventRecords");
        String occurredAt = NamingStrategySupport.stored(strategy, "occurredAt");

        assertThat(stored).containsKey(updatedAt);
        assertThat(stored.get(eventRecords).l()).hasSize(1);
        assertThat(stored.get(eventRecords).l().get(0).m()).containsKey(occurredAt);
        assertThat(strategyName).isNotBlank();
    }
}
