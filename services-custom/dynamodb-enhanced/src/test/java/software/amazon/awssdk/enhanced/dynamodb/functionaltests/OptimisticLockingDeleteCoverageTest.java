    private <T> DynamoDbTable<T> createTable(String logicalName, TableSchema<T> schema) {
        return createTable(enhancedClient, logicalName, schema);
    }

    private <T> DynamoDbTable<T> createTable(DynamoDbEnhancedClient client, String logicalName, TableSchema<T> schema) {
        DynamoDbTable<T> table = client.table(getConcreteTableName(logicalName), schema);
        table.createTable(r -> r.provisionedThroughput(getDefaultProvisionedThroughput()));
        createdTables.add(table.tableName());
        return table;
    }

    private static TableSchema<VersionCounter> versionSchema(StaticAttributeTag versionTag) {
        return StaticTableSchema.builder(VersionCounter.class)
                                .newItemSupplier(VersionCounter::new)
                                .addAttribute(String.class, a -> a.name("id")
                                                                  .getter(VersionCounter::getId)
                                                                  .setter(VersionCounter::setId)
                                                                  .tags(primaryPartitionKey()))
                                .addAttribute(Long.class, a -> a.name("version")
                                                                .getter(VersionCounter::getVersion)
                                                                .setter(VersionCounter::setVersion)
                                                                .tags(versionTag))
                                .build();
    }

