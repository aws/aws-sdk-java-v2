package software.amazon.awssdk.enhanced.dynamodb.mapper;

import static org.assertj.core.api.Assertions.assertThat;
import static software.amazon.awssdk.enhanced.dynamodb.internal.AttributeValues.nullAttributeValue;

import java.util.Collection;
import java.util.Map;
import java.util.stream.Stream;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.Arguments;
import org.junit.jupiter.params.provider.MethodSource;
import software.amazon.awssdk.enhanced.dynamodb.TableMetadata;
import software.amazon.awssdk.enhanced.dynamodb.TableSchema;
import software.amazon.awssdk.enhanced.dynamodb.mapper.NamingMetadataBeans.EmptyChild;
import software.amazon.awssdk.enhanced.dynamodb.mapper.NamingMetadataBeans.EmptyParent;
import software.amazon.awssdk.enhanced.dynamodb.mapper.NamingMetadataBeans.KeyParent;
import software.amazon.awssdk.enhanced.dynamodb.mapper.NamingMetadataBeans.MetadataBean;
import software.amazon.awssdk.enhanced.dynamodb.mapper.UpdateBehavior;
import software.amazon.awssdk.enhanced.dynamodb.model.SearchSchemaElementType;
import software.amazon.awssdk.enhanced.dynamodb.model.VectorIndexMetadata;
import software.amazon.awssdk.services.dynamodb.model.AttributeValue;

/**
 * Checks that tags record the resolved attribute name.
 * Index names stay the values written on the annotations.
 */
class AttributeNamingStrategyMetadataTest {
    private static final String VERSION_KEY = "VersionedRecordExtension:VersionAttribute";
    private static final String TIMESTAMP_KEY = "AutoGeneratedTimestampExtension:AutoGeneratedTimestampAttribute";
    private static final String COUNTER_KEY = "AtomicCounter:Counters";
    private static final String UUID_KEY =
        "software.amazon.awssdk.enhanced.dynamodb.extensions.AutoGeneratedUuidExtension:AutoGeneratedUuidAttribute";

    /**
     * Returns the four built-in strategies and the custom strategy.
     */
    static Stream<Arguments> strategies() {
        return AttributeNamingCases.builtInAndCustom();
    }

    @ParameterizedTest
    @MethodSource("strategies")
    void fromBean_whenTagsPresent_metadataUsesResolvedNames(String label, AttributeNamingStrategy strategy) {
        TableSchema<MetadataBean> schema = TableSchema.fromBean(BeanTableSchemaParams.builder(MetadataBean.class)
                                                                                     .attributeNamingStrategy(strategy)
                                                                                     .build());
        TableMetadata metadata = schema.tableMetadata();
        String orderId = stored(strategy, "orderId");
        String email = stored(strategy, "emailAddress");
        String created = stored(strategy, "createdOn");

        assertThat(metadata.primaryPartitionKey()).isEqualTo(stored(strategy, "id"));
        assertThat(metadata.primarySortKey()).contains(orderId);
        assertThat(metadata.indexPartitionKey(NamingMetadataBeans.GSI_EMAIL)).isEqualTo(email);
        assertThat(metadata.indexSortKey(NamingMetadataBeans.GSI_EMAIL)).contains(created);
        assertThat(metadata.indexSortKey(NamingMetadataBeans.LSI_CREATED)).contains(created);
        assertThat(metadata.indexPartitionKey(NamingMetadataBeans.LSI_CREATED)).isEqualTo(metadata.primaryPartitionKey());
        assertThat(metadata.customMetadataObject(VERSION_KEY, String.class)).contains(stored(strategy, "recordVersion"));
        assertThat(metadata.customMetadataObject(TIMESTAMP_KEY, Collection.class))
            .hasValueSatisfying(names -> assertThat(names).contains(stored(strategy, "updatedAt")));
        assertThat(metadata.customMetadataObject(COUNTER_KEY, Map.class))
            .hasValueSatisfying(counters -> assertThat(counters).containsKey(stored(strategy, "hitCount")));
        assertThat(metadata.customMetadataObject(UUID_KEY, Map.class))
            .hasValueSatisfying(uuids -> assertThat(uuids).containsKey(stored(strategy, "requestId")));
        assertThat(metadata.customMetadataObject("UpdateBehavior:" + stored(strategy, "statusCode"), UpdateBehavior.class))
            .contains(UpdateBehavior.WRITE_IF_NOT_EXISTS);
        assertThat(schema.attributeNames()).contains(stored(strategy, "accountId"), "LEGACY");
        assertThat(schema.attributeNames()).doesNotContain("secret", "cache", stored(strategy, "secret"), stored(strategy, "cache"));

        VectorIndexMetadata vector = metadata.vectorIndices().iterator().next();
        assertThat(vector.indexName()).isEqualTo(NamingMetadataBeans.VECTOR_INDEX);
        assertThat(vector.vectorAttributeName()).isEqualTo(stored(strategy, "productEmbedding"));
        assertThat(vector.searchSchemaElements())
            .anySatisfy(element -> {
                assertThat(element.searchSchemaElementType()).isEqualTo(SearchSchemaElementType.HASH);
                assertThat(element.attributeName()).isEqualTo(stored(strategy, "productCategory"));
            })
            .anySatisfy(element -> {
                assertThat(element.searchSchemaElementType()).isEqualTo(SearchSchemaElementType.INLINE_FILTER);
                assertThat(element.attributeName()).isEqualTo(stored(strategy, "brandName"));
            });
        assertThat(label).isNotBlank();
    }

    @ParameterizedTest
    @MethodSource("strategies")
    void fromBean_whenFlattenedChildHasKeys_parentMetadataUsesResolvedNames(String label,
                                                                            AttributeNamingStrategy strategy) {
        TableSchema<KeyParent> schema = TableSchema.fromBean(BeanTableSchemaParams.builder(KeyParent.class)
                                                                                  .attributeNamingStrategy(strategy)
                                                                                  .build());
        TableMetadata metadata = schema.tableMetadata();

        assertThat(metadata.primaryPartitionKey()).isEqualTo(stored(strategy, "customerId"));
        assertThat(metadata.indexPartitionKey(NamingMetadataBeans.GSI_REGION)).isEqualTo(stored(strategy, "regionCode"));
        assertThat(metadata.indices()).extracting(index -> index.name()).contains(NamingMetadataBeans.GSI_REGION);
        assertThat(label).isNotBlank();
    }

    @ParameterizedTest
    @MethodSource("strategies")
    void fromBean_whenEmptyObjectAndIgnoreNulls_useResolvedNames(String label, AttributeNamingStrategy strategy) {
        TableSchema<EmptyParent> schema = TableSchema.fromBean(BeanTableSchemaParams.builder(EmptyParent.class)
                                                                                    .attributeNamingStrategy(strategy)
                                                                                    .build());
        EmptyParent item = new EmptyParent();
        item.setId("key");
        item.setPreserved(new EmptyChild());
        item.setSkipped(new EmptyChild());
        String preserved = stored(strategy, "preserved");
        String skipped = stored(strategy, "skipped");
        String cityName = stored(strategy, "cityName");

        Map<String, AttributeValue> stored = schema.itemToMap(item, true);

        assertThat(stored).containsKey(preserved);
        assertThat(stored.get(preserved).m()).containsEntry(cityName, nullAttributeValue());
        assertThat(stored.get(skipped).m()).doesNotContainKey(cityName);
        assertThat(schema.mapToItem(stored).getPreserved()).isNotNull();
        assertThat(label).isNotBlank();
    }

    /**
     * Returns the stored name for a source name.
     */
    private static String stored(AttributeNamingStrategy strategy, String sourceName) {
        return AttributeNamingCases.storedName(strategy, sourceName);
    }
}
