    private void removeNestedWriteOnce(String id) {
        Map<String, String> names = new HashMap<>();
        names.put("#child", "child");
        names.put("#writeOnce", "childWriteOnce");
        Map<String, AttributeValue> key = Collections.singletonMap("id", AttributeValue.fromS(id));
        getDynamoDbClient().updateItem(r -> r.tableName(currentTestTableName)
                                             .key(key)
                                             .updateExpression("REMOVE #child.#writeOnce")
                                             .expressionAttributeNames(names));
        Map<String, AttributeValue> persisted = getDynamoDbClient().getItem(r -> r.tableName(currentTestTableName)
                                                                                  .key(key)).item();
        assertThat(persisted.get("child").m()).doesNotContainKey("childWriteOnce");
    }

    private <T> DynamoDbTable<T> createAndPut(String tableSuffix, TableSchema<T> schema, T item) {
        currentTestTableName = BASE_TABLE_NAME + tableSuffix + System.nanoTime();
        DynamoDbTable<T> table = enhancedClient.table(currentTestTableName, schema);
        table.createTable(r -> r.provisionedThroughput(getDefaultProvisionedThroughput()));
        table.putItem(item);
        return table;
    }
