    public void transactUpdate_nestedTagsAndCondition_preserveAtomicMixedSchemaWrites() {
        DynamoDbTable<BeanWithImmutableChild> supported = createAndPut("transaction-supported",
                                                                       BeanTableSchema.create(BeanWithImmutableChild.class),
                                                                       new BeanWithImmutableChild().setId("supported").setNote(
                                                                                                       "allow")
                                                                                                   .setChild(immutableChild(
                                                                                                       "old-always",
                                                                                                       "old-once")));
        String customTableName = BASE_TABLE_NAME + "transaction-unsupported" + System.nanoTime();
        DynamoDbTable<Map<String, AttributeValue>> unsupported =
            enhancedClient.table(customTableName, new UnsupportedConverterTableSchema());
        unsupported.createTable(r -> r.provisionedThroughput(getDefaultProvisionedThroughput()));
        try {
            Expression allowed = Expression.builder().expression("#note = :expected")
                                           .expressionNames(Collections.singletonMap("#note", "note"))
                                           .expressionValues(Collections.singletonMap(":expected", AttributeValue.fromS("allow")))
                                           .build();
            BeanWithImmutableChild update = new BeanWithImmutableChild().setId("supported").setNote("allow")
                                                                        .setChild(immutableChild("new-always", "new-once"));
            TransactUpdateItemEnhancedRequest<BeanWithImmutableChild> allowedUpdate =
                TransactUpdateItemEnhancedRequest.builder(BeanWithImmutableChild.class)
                                                 .item(update)
                                                 .ignoreNullsMode(IgnoreNullsMode.SCALAR_ONLY)
                                                 .conditionExpression(allowed)
                                                 .build();
            Map<String, AttributeValue> custom = new HashMap<>();
            custom.put("pk", AttributeValue.fromS("custom-success"));
            custom.put("value", AttributeValue.fromS("stored"));

            enhancedClient.transactWriteItems(r -> r.addUpdateItem(supported, allowedUpdate)
                                                    .addPutItem(unsupported, custom));
            NestedImmutableChild persisted = supported.getItem(r -> r.key(k -> k.partitionValue("supported")))
                                                      .getChild();
            assertThat(persisted.getChildAlwaysUpdate()).isEqualTo("new-always");
            assertThat(persisted.getChildWriteOnce()).isEqualTo("old-once");
            assertThat(unsupported.getItem(r -> r.key(k -> k.partitionValue("custom-success"))).get("value").s())
                .isEqualTo("stored");

            Expression denied = Expression.builder().expression("#note = :expected")
                                          .expressionNames(Collections.singletonMap("#note", "note"))
                                          .expressionValues(Collections.singletonMap(":expected", AttributeValue.fromS("deny")))
                                          .build();
            BeanWithImmutableChild rejected = new BeanWithImmutableChild().setId("supported")
                                                                          .setChild(immutableChild("rejected-always", "rejected"
                                                                                                                      + "-once"));
            TransactUpdateItemEnhancedRequest<BeanWithImmutableChild> deniedUpdate =
                TransactUpdateItemEnhancedRequest.builder(BeanWithImmutableChild.class)
                                                 .item(rejected)
                                                 .ignoreNullsMode(IgnoreNullsMode.SCALAR_ONLY)
                                                 .conditionExpression(denied)
                                                 .build();
            Map<String, AttributeValue> rejectedCustom = new HashMap<>();
            rejectedCustom.put("pk", AttributeValue.fromS("custom-rejected"));
            rejectedCustom.put("value", AttributeValue.fromS("not-stored"));

            assertThatThrownBy(() -> enhancedClient.transactWriteItems(r -> r.addUpdateItem(supported, deniedUpdate)
                                                                             .addPutItem(unsupported, rejectedCustom)))
                .isInstanceOf(TransactionCanceledException.class);
            NestedImmutableChild afterFailure = supported.getItem(r -> r.key(k -> k.partitionValue("supported")))
                                                         .getChild();
            assertThat(afterFailure.getChildAlwaysUpdate()).isEqualTo("new-always");
            assertThat(afterFailure.getChildWriteOnce()).isEqualTo("old-once");
            assertThat(unsupported.getItem(r -> r.key(k -> k.partitionValue("custom-rejected")))).isNull();
        } finally {
            getDynamoDbClient().deleteTable(r -> r.tableName(customTableName));
        }
    }

