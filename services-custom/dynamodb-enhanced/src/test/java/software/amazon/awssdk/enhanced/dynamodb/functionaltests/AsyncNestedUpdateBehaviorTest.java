package software.amazon.awssdk.enhanced.dynamodb.functionaltests;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.util.Collections;
import java.util.HashMap;
import java.util.Map;
import java.util.concurrent.CompletionException;
import org.junit.After;
import org.junit.Before;
import org.junit.Test;
import software.amazon.awssdk.enhanced.dynamodb.DynamoDbAsyncTable;
import software.amazon.awssdk.enhanced.dynamodb.DynamoDbEnhancedAsyncClient;
import software.amazon.awssdk.enhanced.dynamodb.Expression;
import software.amazon.awssdk.enhanced.dynamodb.TableSchema;
import software.amazon.awssdk.enhanced.dynamodb.extensions.AutoGeneratedTimestampRecordExtension;
import software.amazon.awssdk.enhanced.dynamodb.functionaltests.models.UnsupportedConverterTableSchema;
import software.amazon.awssdk.enhanced.dynamodb.functionaltests.models.UpdateBehaviorTestModels.BeanWithImmutableChild;
import software.amazon.awssdk.enhanced.dynamodb.functionaltests.models.UpdateBehaviorTestModels.NestedImmutableChild;
import software.amazon.awssdk.enhanced.dynamodb.mapper.BeanTableSchema;
import software.amazon.awssdk.enhanced.dynamodb.model.IgnoreNullsMode;
import software.amazon.awssdk.enhanced.dynamodb.model.TransactUpdateItemEnhancedRequest;
import software.amazon.awssdk.services.dynamodb.model.AttributeValue;
import software.amazon.awssdk.services.dynamodb.model.TransactionCanceledException;

public class AsyncNestedUpdateBehaviorTest extends LocalDynamoDbAsyncTestBase {

    private final DynamoDbEnhancedAsyncClient enhancedClient = DynamoDbEnhancedAsyncClient.builder()
                                                                                          .dynamoDbClient(getDynamoDbAsyncClient())
                                                                                          .extensions(AutoGeneratedTimestampRecordExtension.create())
                                                                                          .build();
    private final String supportedName = getConcreteTableName("nested-update-behavior-supported");
    private final String unsupportedName = getConcreteTableName("nested-update-behavior-unsupported");
    private final TableSchema<BeanWithImmutableChild> supportedSchema = BeanTableSchema.create(BeanWithImmutableChild.class);
    private final DynamoDbAsyncTable<BeanWithImmutableChild> supported = enhancedClient.table(supportedName, supportedSchema);
    private final DynamoDbAsyncTable<Map<String, AttributeValue>> unsupported =
        enhancedClient.table(unsupportedName, new UnsupportedConverterTableSchema());

    @Before
    public void createTables() {
        supported.createTable(r -> r.provisionedThroughput(getDefaultProvisionedThroughput())).join();
        unsupported.createTable(r -> r.provisionedThroughput(getDefaultProvisionedThroughput())).join();
    }

    @After
    public void deleteTables() {
        getDynamoDbAsyncClient().deleteTable(r -> r.tableName(supportedName)).join();
        getDynamoDbAsyncClient().deleteTable(r -> r.tableName(unsupportedName)).join();
    }

    @Test
    public void sharedClient_unsupportedSchemaDoesNotAffectNestedTaggedUpdate() {
        supported.putItem(new BeanWithImmutableChild().setId("supported")
                                                      .setChild(child("old-always", "old-once"))).join();
        Map<String, AttributeValue> custom = new HashMap<>();
        custom.put("pk", AttributeValue.fromS("custom"));
        custom.put("child", AttributeValue.builder().m(Collections.singletonMap("name", AttributeValue.fromS("old")))
                                          .build());
        unsupported.putItem(custom).join();

        custom.put("child", AttributeValue.builder().m(Collections.singletonMap("name", AttributeValue.fromS("new")))
                                          .build());
        unsupported.updateItem(r -> r.item(custom).ignoreNullsMode(IgnoreNullsMode.SCALAR_ONLY)).join();
        supported.updateItem(r -> r.item(new BeanWithImmutableChild().setId("supported")
                                                                     .setChild(child("new-always", "new-once"))).ignoreNullsMode(IgnoreNullsMode.SCALAR_ONLY)).join();

        assertThat(unsupported.getItem(r -> r.key(k -> k.partitionValue("custom"))).join()
                              .get("child").m().get("name").s()).isEqualTo("new");
        NestedImmutableChild persisted = supported.getItem(r -> r.key(k -> k.partitionValue("supported"))).join()
                                                  .getChild();
        assertThat(persisted.getChildAlwaysUpdate()).isEqualTo("new-always");
        assertThat(persisted.getChildWriteOnce()).isEqualTo("old-once");
    }

    @Test
    public void transactUpdate_nestedTagsAndCondition_preserveAtomicMixedSchemaWrites() {
        supported.putItem(new BeanWithImmutableChild().setId("supported").setNote("allow")
                                                      .setChild(child("old-always", "old-once"))).join();
        Expression allowed = noteEquals("allow");
        TransactUpdateItemEnhancedRequest<BeanWithImmutableChild> allowedUpdate =
            TransactUpdateItemEnhancedRequest.builder(BeanWithImmutableChild.class)
                                             .item(new BeanWithImmutableChild().setId("supported").setNote("allow")
                                                                               .setChild(child("new-always", "new-once")))
                                             .ignoreNullsMode(IgnoreNullsMode.SCALAR_ONLY)
                                             .conditionExpression(allowed)
                                             .build();
        Map<String, AttributeValue> custom = new HashMap<>();
        custom.put("pk", AttributeValue.fromS("custom-success"));
        custom.put("value", AttributeValue.fromS("stored"));

        enhancedClient.transactWriteItems(r -> r.addUpdateItem(supported, allowedUpdate)
                                                .addPutItem(unsupported, custom)).join();
        NestedImmutableChild persisted = supported.getItem(r -> r.key(k -> k.partitionValue("supported"))).join()
                                                  .getChild();
        assertThat(persisted.getChildAlwaysUpdate()).isEqualTo("new-always");
        assertThat(persisted.getChildWriteOnce()).isEqualTo("old-once");
        assertThat(unsupported.getItem(r -> r.key(k -> k.partitionValue("custom-success"))).join().get("value").s())
            .isEqualTo("stored");

        TransactUpdateItemEnhancedRequest<BeanWithImmutableChild> deniedUpdate =
            TransactUpdateItemEnhancedRequest.builder(BeanWithImmutableChild.class)
                                             .item(new BeanWithImmutableChild().setId("supported")
                                                                               .setChild(child("rejected-always", "rejected"
                                                                                                                  + "-once")))
                                             .ignoreNullsMode(IgnoreNullsMode.SCALAR_ONLY)
                                             .conditionExpression(noteEquals("deny"))
                                             .build();
        Map<String, AttributeValue> rejectedCustom = new HashMap<>();
        rejectedCustom.put("pk", AttributeValue.fromS("custom-rejected"));
        rejectedCustom.put("value", AttributeValue.fromS("not-stored"));

        assertThatThrownBy(() -> enhancedClient.transactWriteItems(r -> r.addUpdateItem(supported, deniedUpdate)
                                                                         .addPutItem(unsupported, rejectedCustom)).join())
            .isInstanceOf(CompletionException.class)
            .hasCauseInstanceOf(TransactionCanceledException.class);
        NestedImmutableChild afterFailure = supported.getItem(r -> r.key(k -> k.partitionValue("supported"))).join()
                                                     .getChild();
        assertThat(afterFailure.getChildAlwaysUpdate()).isEqualTo("new-always");
        assertThat(afterFailure.getChildWriteOnce()).isEqualTo("old-once");
        assertThat(unsupported.getItem(r -> r.key(k -> k.partitionValue("custom-rejected"))).join()).isNull();
    }

    private static NestedImmutableChild child(String always, String once) {
        return NestedImmutableChild.builder().childAlwaysUpdate(always).childWriteOnce(once).build();
    }

    private static Expression noteEquals(String value) {
        return Expression.builder().expression("#note = :expected")
                         .expressionNames(Collections.singletonMap("#note", "note"))
                         .expressionValues(Collections.singletonMap(":expected", AttributeValue.fromS(value)))
                         .build();
    }
}
