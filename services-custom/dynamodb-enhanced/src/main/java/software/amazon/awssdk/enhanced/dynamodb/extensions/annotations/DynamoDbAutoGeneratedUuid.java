package software.amazon.awssdk.enhanced.dynamodb.extensions.annotations;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;
import software.amazon.awssdk.annotations.SdkPublicApi;
import software.amazon.awssdk.enhanced.dynamodb.internal.extensions.AutoGeneratedUuidTag;
import software.amazon.awssdk.enhanced.dynamodb.mapper.annotations.BeanTableSchemaAttributeTag;

/**
 * Denotes this attribute as recording the auto generated UUID string for the record.
 * <p>
 * The {@link #strategy()} controls whether UUID is generated on every write or only when missing.
 * The default is {@link DynamoDbAutoGenerateStrategy#ALWAYS} for backward compatibility with existing
 * {@code @DynamoDbAutoGeneratedUuid} usage.
 * Use {@link DynamoDbAutoGenerateStrategy#CREATE} to generate a UUID only when
 * the attribute is missing. In the write item map, an explicit DynamoDB
 * {@code NULL} value is considered missing, while an empty string is considered
 * present.
 * <p>
 * For a non-primary-key {@code CREATE} attribute omitted from an {@code updateItem} write item map, the extension uses
 * {@code if_not_exists} so DynamoDB applies the supplied UUID only when the stored attribute is absent. An existing stored
 * value, including DynamoDB {@code NULL} or an empty string, is preserved. An explicit DynamoDB {@code NULL} in the write item
 * map is instead replaced with a generated UUID before the request is sent.
 * <p>
 * {@code putItem} is a full replacement operation, so every put whose {@code CREATE} value is missing generates a UUID,
 * including a subsequent put using the same primary key.
 */
@SdkPublicApi
@Target(ElementType.METHOD)
@Retention(RetentionPolicy.RUNTIME)
@BeanTableSchemaAttributeTag(AutoGeneratedUuidTag.class)
public @interface DynamoDbAutoGeneratedUuid {
    /**
     * Defines when a new UUID should be generated.
     * <p>
     * Defaults to {@link DynamoDbAutoGenerateStrategy#ALWAYS} to preserve backward compatibility.
     */
    DynamoDbAutoGenerateStrategy strategy() default DynamoDbAutoGenerateStrategy.ALWAYS;
}
